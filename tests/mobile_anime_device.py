"""Opt-in regression on the installed Samsung WebView. No separate browser.

Requires signed SourceRemovalInstrumentation with auditDebug and an ADB CDP
forward. Real playback reads the installed providers. Continuity writes are
intercepted; list/rating/download mutations are never invoked. Controlled error
fixtures exist only for the duration of this connection.
"""
import argparse, asyncio, json, shutil, subprocess
from pathlib import Path
from playwright.async_api import async_playwright

async def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', required=True)
    parser.add_argument('--cdp', default='http://127.0.0.1:19222')
    opt = parser.parse_args()
    out = Path(opt.output); out.mkdir(parents=True, exist_ok=True)
    adb = [shutil.which('adb'), '-s', 'R3CT60PD7YA']
    results = []; sources = []; errors = []; blocked = []
    def check(name, ok, detail=None):
        results.append(dict(name=name, passed=bool(ok), detail=detail))
        (out/'anime-device-checks.json').write_text(json.dumps(results, indent=2), encoding='utf8')
        assert ok, name
    def back(): subprocess.run([*adb, 'shell', 'input', 'keyevent', '4'], check=True, capture_output=True)
    async with async_playwright() as pw:
        browser = await pw.chromium.connect_over_cdp(opt.cdp)
        page = next(p for c in browser.contexts for p in c.pages if ':43211' in p.url)
        page.set_default_timeout(30000)
        page.on('pageerror', lambda e: errors.append(str(e)))
        def requested(r):
            if '/onlinestream/episode-source' in r.url: sources.append(r.post_data_json)
        page.on('request', requested)
        async def continuity(r):
            if r.request.method == 'PATCH':
                blocked.append(r.request.post_data_json)
                await r.fulfill(json={'data': True})
            else: await r.continue_()
        await page.route('**/api/v1/continuity/item', continuity)
        session = await page.context.new_cdp_session(page)
        async def shot(name):
            await page.screenshot(path=str(out/name))
        async def home():
            await page.locator('#__seanime_bottom_nav [data-nav-id="home"]').click()
            await page.locator('[data-home-episode-card]').first.wait_for()
        async def pause(): await page.evaluate('document.querySelectorAll("video").forEach(v=>v.pause())')
        async def wait_source():
            await page.wait_for_function('!!document.querySelector("video")?.duration', timeout=60000)
            await pause()
        storage = await page.evaluate('Object.fromEntries(Object.entries(localStorage))')
        try:
            await home()
            # Home no longer has a details link; open the continued series' page directly.
            href = await page.evaluate("(async()=>{const id=document.querySelector('[data-home-episode-card]').dataset.mediaId;history.pushState({},'','/entry?id='+id);dispatchEvent(new PopStateEvent('popstate'));return '/entry?id='+id})()")
            await page.locator('.mobile-anime-header').wait_for()
            check('Home series details opens the matching anime', href in page.url)
            await wait_source()
            await page.evaluate('scrollTo(0,0)'); await shot('after-anime.png')
            check('Android React header replaces the old injected More info widget', await page.locator('#__seanime_moreinfo_wrapper').count() == 0)
            await page.locator('.mobile-anime-details summary').click()
            check('Expandable metadata includes full long title and original description', await page.locator('.mobile-anime-details[open]').count() == 1 and len(await page.locator('.mobile-anime-details').inner_text()) > 200)
            await shot('after-anime-details.png')
            await page.locator('.mobile-anime-details summary').click()
            await page.get_by_role('button', name='Edit list, progress and rating', exact=True).click()
            await page.get_by_role('dialog').wait_for()
            check('Original list, progress and rating form opens in contained dialog', await page.locator('.mobile-anime-dialog input').count() > 0)
            check('Compact AniList sheet: status chips and the whole form visible without scrolling', await page.get_by_role('radio').count() >= 1 and await page.get_by_role('dialog').evaluate('e=>{const r=e.getBoundingClientRect();return e.scrollHeight<=e.clientHeight+1&&r.top>=0&&r.bottom<=innerHeight+1}'))
            await shot('after-anilist-sheet.png')
            back(); await page.get_by_role('dialog').wait_for(state='hidden')
            check('Android Back closes list form without leaving anime', href in page.url)
            check('AniList edit action is a clear 48dp+ target', await page.locator('[data-anilist-media-entry-modal-edit-button]').evaluate('e=>{const r=e.getBoundingClientRect();return r.width>=48&&r.height>=48}'))
            await page.locator('.mobile-anime-episodes-link').click()
            check('Source, audio and download options are visible without expanding', await page.locator('.mobile-episode-options .mobile-source-pair').count() == 1 and await page.get_by_role('combobox', name='Provider', exact=True).is_visible() and await page.locator('.mobile-source-segment button[aria-pressed=true]').count() == 1)
            check('Audio toggle reads Sub / Dub with a descriptive subtitles label', await page.locator('.mobile-source-segment button').first.evaluate('e=>e.textContent.trim()==="Sub"&&/^(Subtitles|Untertitel)$/.test(e.getAttribute("aria-label"))'))
            check('Exactly one download button on the anime page', await page.evaluate('''[...document.querySelectorAll('[data-mobile-anime] button')].filter(b=>/download/i.test(b.textContent+' '+(b.getAttribute('aria-label')||''))).length''') == 1 and await page.locator('[data-download-season]').count() == 1)
            check('Provider icon sits inside the provider pill', await page.locator('.mobile-source-pair .UI-InputAddon__root').count() == 0)
            check('No separate Play / continue button and no heading marks', await page.locator('.mobile-episode-play').count() == 0 and await page.evaluate('''[...document.querySelectorAll('[data-mobile-anime] h2')].every(h=>getComputedStyle(h,'::before').content==='none')'''))
            await page.get_by_role('combobox', name='Provider', exact=True).click()
            await page.get_by_role('listbox').wait_for()
            await page.locator('[role=option][data-state=checked]').wait_for()
            check('Provider selection exposes selected option', await page.locator('[role=option][data-state=checked]').count() == 1)
            await shot('after-source-selection.png')
            back(); await page.get_by_role('listbox').wait_for(state='hidden')
            check('Android Back closes provider selection first', href in page.url)
            await page.get_by_role('combobox', name='Server', exact=True).click()
            await page.get_by_role('listbox').wait_for(); back(); await page.get_by_role('listbox').wait_for(state='hidden')
            check('Android Back closes server selection first', href in page.url)
            await page.get_by_role('button', name='Manual match', exact=True).click()
            await page.get_by_role('dialog').wait_for()
            check('Manual mapping remains available in one dialog', await page.get_by_role('dialog').count() == 1)
            await page.get_by_role('dialog').locator('input').first.focus()
            await page.get_by_role('dialog').locator('input').first.fill('Controlled input – no search or mapping submitted')
            await shot('after-mapping-keyboard.png')
            await page.keyboard.press('Escape'); back()
            await page.get_by_role('dialog').wait_for(state='hidden')
            await page.get_by_role('button', name='Download season / episodes', exact=True).click()
            await page.get_by_role('dialog').wait_for()
            check('Existing season download selection remains available without queueing', await page.locator('[data-episode-download-picker]').count() == 1)
            current = await page.locator('[data-episode-grid-item][data-is-selected=true]').get_attribute('data-episode-number')
            this = page.locator('[data-download-preset="this"]')
            if await this.is_enabled():
                await this.click()
                check('"This episode" selects only the current episode (nothing queued)', await page.evaluate('[...document.querySelectorAll("[data-download-episode] input")].filter(i=>i.checked).map(i=>i.closest("label").dataset.downloadEpisode).join()') == current)
            else:
                check('"This episode" is disabled because the current episode is already saved', await page.locator(f'[data-download-episode="{current}"][data-saved]').count() == 1)
            await shot('after-download-sheet.png')
            back(); await page.get_by_role('dialog').wait_for(state='hidden')
            await page.locator('.mobile-episode-heading').scroll_into_view_if_needed()
            await shot('after-episode.png')
            check('Episode heading does not repeat the anime title', await page.locator('.mobile-episode-heading p').count() == 0 and (await page.locator('.mobile-anime-title h1').inner_text()).strip() not in await page.locator('.mobile-episode-heading').inner_text())
            original_episode = await page.locator('[data-episode-grid-item][data-is-selected=true]').get_attribute('data-episode-number')
            cards = page.locator('[data-episode-grid-item]')
            info = cards.first.get_by_role('button', name='Episode 1: Info', exact=True)
            await info.click(); await page.get_by_role('dialog').wait_for()
            check('Secondary episode info does not change selection or open playback', await page.locator('[data-episode-grid-item][data-is-selected=true]').get_attribute('data-episode-number') == original_episode)
            back(); await page.get_by_role('dialog').wait_for(state='hidden')
            sources.clear()
            target = 3 if original_episode == '2' else 2
            await page.locator(f'#episode-{target} .mobile-episode-target').evaluate('e=>{e.click();e.click();e.click()}')
            await page.wait_for_function('(n)=>document.querySelector("#episode-"+n)?.dataset.isSelected==="true"', arg=target)
            await wait_source()
            check('Rapid repeated episode selection creates one source request', len([s for s in sources if s.get('episodeNumber') == target]) == 1, sources)
            await page.get_by_role('button', name='Next episode', exact=True).click(); await wait_source()
            check('Next episode selects the adjacent available episode', await page.locator(f'#episode-{target+1}').get_attribute('data-is-selected') == 'true')
            await page.get_by_role('button', name='Previous episode', exact=True).click(); await wait_source()
            check('Previous episode returns to the correct episode', await page.locator(f'#episode-{target}').get_attribute('data-is-selected') == 'true')
            await page.locator('[title="Switch to grid view"]').click()
            await page.locator('.mobile-episode-target').first.wait_for(state='hidden')
            check('Original episode grid mode remains available', await page.locator('.mobile-episode-target').count() == 0)
            await page.locator('[title="Switch to list view"]').click()
            await page.locator('.mobile-episode-target').first.wait_for()
            await session.send('Emulation.setDeviceMetricsOverride', dict(width=320,height=740,deviceScaleFactor=3,mobile=True))
            await page.evaluate('document.documentElement.style.fontSize="200%";scrollTo(0,0)')
            check('320 CSS pixels at 200 percent text has no page overflow', await page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
            check('320 CSS pixels at 200 percent text keeps the header content on screen', await page.evaluate('''[...document.querySelectorAll('.mobile-anime-header-inner > *, .mobile-anime-title, .mobile-anime-progress button')].every(e=>{const r=e.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth+1})'''))
            await shot('anime-320-200.png')
            await page.locator('#episode-2').scroll_into_view_if_needed()
            check('Large text retains separate reachable episode and info targets', await page.locator('#episode-2 .mobile-episode-target').evaluate('e=>{let r=e.getBoundingClientRect();return r.height>=44&&r.width>=44}') and await page.locator('#episode-2 [data-episode-grid-item-action] button').first.evaluate('e=>{let r=e.getBoundingClientRect();return r.height>=43.9&&r.width>=43.9}'))
            await shot('episodes-320-200.png')
            await page.evaluate('document.documentElement.style.fontSize=""')
            await session.send('Emulation.clearDeviceMetricsOverride')
            await page.emulate_media(reduced_motion='reduce')
            check('Reduced motion removes entry transition animation', await page.locator('.mobile-anime-episodes-link').evaluate('e=>getComputedStyle(e).transitionDuration==="0s"'))
            await page.emulate_media(reduced_motion='no-preference')
            await home()
            await page.locator('[data-library-collection-list-item-media-card-lazy-grid][data-list-type=CURRENT] a[href="'+href+'"]').first.click()
            await page.locator('.mobile-anime-header').wait_for(); await wait_source()
            check('Second Home library-card entry preserves the selected episode', await page.locator(f'#episode-{target}').get_attribute('data-is-selected') == 'true')
            await page.evaluate('scrollTo(0,0)')
            frames = await page.evaluate('''async()=>{let a=[],last=performance.now();for(let i=0;i<120;i++){await new Promise(requestAnimationFrame);let now=performance.now();a.push(now-last);last=now;scrollTo(0,(i<60?i:120-i)*20)}scrollTo(0,0);return a}''')
            await session.send('Performance.enable')
            metrics = await session.send('Performance.getMetrics')
            (out/'after-performance.json').write_text(json.dumps(dict(frames=frames,metrics=metrics),indent=2))
            check('Single mobile episode scrolling surface', await page.locator('[data-vc-element="inline-layout-episode-list-container"]').evaluate('e=>getComputedStyle(e).overflowY==="visible"'))
            check('No uncaught page errors', not errors, errors)
        finally:
            await pause()
            await page.evaluate('document.documentElement.style.fontSize=""')
            await session.send('Emulation.clearDeviceMetricsOverride')
            await page.emulate_media(reduced_motion='no-preference')
            # Restore only storage keys actually changed by these interactions.
            await page.evaluate('before=>{for(const k of new Set([...Object.keys(before),...Object.keys(localStorage)])){if(localStorage.getItem(k)!==(before[k]??null)){if(k.startsWith("sea-onlinestream")||k.startsWith("sea-video-core")){if(k in before)localStorage.setItem(k,before[k]);else localStorage.removeItem(k)}}}}', storage)
            await home()
            (out/'blocked-continuity-writes.json').write_text(json.dumps(blocked,indent=2))
            await page.unroute('**/api/v1/continuity/item', continuity)
            await browser.close()

asyncio.run(main())
