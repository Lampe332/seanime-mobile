"""Full production React playlist workflow with isolated API boundaries; no live writes."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import subprocess, tempfile, json, sys

ROOT = Path(__file__).resolve().parents[1]
results = []

def check(name, passed):
    results.append({'name': name, 'passed': bool(passed)})
    assert passed, name

with tempfile.TemporaryDirectory(prefix='seanime-playlist-ui-') as temp:
    bundle = Path(temp) / 'playlists.js'
    subprocess.run(['node', str(ROOT / 'tests/mobile_playlists_bundle.cjs'), str(bundle)], cwd=ROOT, check=True)
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=True)
        page = browser.new_page(viewport={'width': 320, 'height': 720}, is_mobile=True, has_touch=True)
        errors = []
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.route('http://playlists.test/**', lambda route: route.fulfill(content_type='text/html', body='''<html><head><meta name="viewport" content="width=device-width,initial-scale=1"><style>*{box-sizing:border-box}body{margin:0;background:#100d17;color:white;font:16px sans-serif}button,input,select{font:inherit;color:inherit}button{min-height:44px;border-radius:10px;background:#3a2951;border:1px solid #69517e;padding:8px}button:disabled{opacity:.4}.w-full{width:100%}.inline-flex{display:inline-flex}.whitespace-nowrap{white-space:nowrap}h1,h2,p{margin:0}.sr-only{position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0,0,0,0)}</style></head><body><div id="root"></div></body></html>'''))
        page.goto('http://playlists.test/')
        page.add_style_tag(path=str(bundle.with_suffix('.css')))
        page.add_script_tag(path=str(bundle))
        sheet = page.locator('.mobile-playlists')
        def button(name): return sheet.get_by_role('button', name=name, exact=True)
        def back():
            page.evaluate('window.dispatchEvent(new Event("seanime:android-back",{cancelable:true}))')
            sheet.locator('.mp-anime').first.wait_for()
        def name_input(): return sheet.locator('.mp-field input').first
        def create(): button('Create playlist').click()
        def anime_first(): sheet.locator('.mp-anime').first.click()
        def choose(number): button(f'Episode {number}').click()
        page.get_by_role('button', name='Open playlists', exact=True).click()
        check('Existing playlists visible before any edit', sheet.get_by_text('Protected original', exact=True).is_visible())
        create()
        name_input().fill('Controlled regression playlist')
        button('Add episodes').click()
        check('Only one dialog across overview and anime selection', page.get_by_role('dialog').count() == 1)
        anime_first()
        choose(1)
        check('Episode selection exposes accessible selected state and count', button('Episode 1').get_attribute('aria-pressed') == 'true' and sheet.get_by_text('1 / 3 selected', exact=True).is_visible())
        back()
        check('Android Back returns from episodes to anime without losing draft', sheet.locator('.mp-anime').count() == 1)
        anime_first()
        check('Selected episode survives return to anime and reopen', button('Episode 1').get_attribute('aria-pressed') == 'true')
        button('Select all').click()
        check('Bulk selection selects every episode', sheet.locator('.mp-episode-choice[aria-pressed=true]').count() == 3)
        button('Deselect all').click()
        check('Bulk deselection keeps selection consistent', sheet.locator('.mp-episode-choice[aria-pressed=true]').count() == 0)
        choose(1)
        choose(2)
        back()
        search = sheet.get_by_placeholder('Search anime…')
        search.fill('Second')
        check('Search includes planned anime and disables category', sheet.locator('.mp-anime').count() == 1 and sheet.locator('select').is_disabled())
        anime_first()
        choose(1)
        button('Review selection · 3').click()
        check('Selection confirmation returns to named draft with multi-anime order', name_input().input_value() == 'Controlled regression playlist' and sheet.locator('.mp-episode-edit').count() == 3)
        check('No backend write before explicit saving', page.evaluate('playlistProbe.writes.length') == 0)
        sheet.get_by_role('button', name='Move episode up', exact=True).nth(2).click()
        check('Accessible reorder moves selected episode', sheet.locator('.mp-episode-edit .mp-copy small').nth(1).inner_text() == 'Anime 2')
        sheet.get_by_role('button', name='Remove episode', exact=True).nth(2).click()
        check('Remove affects draft only', sheet.locator('.mp-episode-edit').count() == 2 and page.evaluate('playlistProbe.state.playlists[0].episodes.length') == 1)
        sheet.locator('select').last.select_option('debrid')
        page.evaluate('playlistProbe.update({fail:true})')
        button('Save playlist').click()
        sheet.get_by_role('alert').wait_for()
        check('Failed save retains draft and selection', name_input().input_value() == 'Controlled regression playlist' and sheet.locator('.mp-episode-edit').count() == 2)
        page.evaluate('playlistProbe.update({fail:false});playlistProbe.writes.length=0')
        button('Save playlist').evaluate('e=>{e.click();e.click();e.click()}')
        page.wait_for_function('playlistProbe.state.playlists.length===2')
        check('Rapid repeated save creates exactly one playlist', page.evaluate('playlistProbe.writes.length') == 1)
        saved = page.evaluate('playlistProbe.state.playlists[1]')
        check('Stored episode order, source, and existing data preserved', [x['episode']['baseAnime']['id'] for x in saved['episodes']] == [1,2] and saved['episodes'][1]['watchType'] == 'debrid' and page.evaluate('playlistProbe.state.playlists[0].name') == 'Protected original')
        sheet.get_by_role('button', name='Edit: Controlled regression playlist', exact=True).click()
        check('Reopen saved playlist restores name and episodes', name_input().input_value() == 'Controlled regression playlist' and sheet.locator('.mp-episode-edit').count() == 2)
        name_input().fill('Controlled edited playlist')
        button('Save playlist').click()
        page.wait_for_function('playlistProbe.state.playlists[1].name==="Controlled edited playlist"')
        sheet.get_by_role('button', name='Edit: Controlled edited playlist', exact=True).click()
        button('Delete playlist').click()
        check('Delete requires its own confirmation screen', sheet.get_by_text('Delete playlist?', exact=True).is_visible() and len(page.evaluate('playlistProbe.state.playlists')) == 2)
        button('Cancel').click()
        check('Cancelling deletion preserves saved playlist and draft', name_input().input_value() == 'Controlled edited playlist' and len(page.evaluate('playlistProbe.state.playlists')) == 2)
        button('Delete playlist').click()
        button('Delete').evaluate('e=>{e.click();e.click()}')
        page.wait_for_function('playlistProbe.state.playlists.length===1')
        check('Delete lock removes only chosen test playlist', page.evaluate('playlistProbe.writes.filter(x=>x.type==="delete").length') == 1 and page.evaluate('playlistProbe.state.playlists[0].dbId') == 99)
        create()
        name_input().fill('Never save this draft')
        button('Add episodes').click()
        anime_first()
        choose(1)
        button('Review selection · 1').click()
        button('Discard draft').click()
        check('Discard does not create incomplete playlist', page.evaluate('playlistProbe.state.playlists.length') == 1)
        sheet.get_by_role('button', name='Play: Protected original', exact=True).click()
        check('Explicit Play passes original playlist unchanged and closes workspace', page.evaluate('playlistProbe.plays[0].dbId') == 99 and not sheet.is_visible())
        page.evaluate('playlistProbe.update({selectedMedia:2,episodeToAdd:"2",open:true})')
        button('Add to new playlist').click()
        page.wait_for_function('document.querySelector(".mp-episode-choice[aria-pressed=true]")')
        check('Existing external anime/episode entry point selects requested episode', button('Episode 2').get_attribute('aria-pressed') == 'true')
        button('Review selection · 1').click()
        check('External episode selection stays an unsaved draft', page.evaluate('playlistProbe.state.playlists.length') == 1)
        sheet.locator('.mobile-workspace-close').click()
        page.evaluate('playlistProbe.update({selectedMedia:1,episodeToAdd:"2",blockedMedia:1,open:true})')
        button('Add to new playlist').click()
        sheet.get_by_role('status').wait_for()
        back()
        sheet.get_by_placeholder('Search anime…').fill('Second')
        anime_first()
        check('Delayed external request cannot select same episode number from another anime', sheet.locator('.mp-episode-choice[aria-pressed=true]').count() == 0 and page.evaluate('playlistProbe.state.episodeToAdd') == '2')
        back()
        page.evaluate('playlistProbe.update({blockedMedia:null})')
        sheet.get_by_placeholder('Search anime…').fill('')
        anime_first()
        button('Episode 2').wait_for()
        check('Original external anime request survives detour and selects correct episode', button('Episode 2').get_attribute('aria-pressed') == 'true')
        button('Review selection · 1').click()
        page.evaluate('document.documentElement.style.fontSize="200%"')
        button('Add episodes').click()
        sheet.locator('.mp-anime').last.scroll_into_view_if_needed()
        check('320 CSS pixels and 200 percent text have no horizontal overflow', sheet.evaluate('e=>e.scrollWidth<=e.clientWidth+1') and sheet.locator('.mp-anime').last.evaluate('e=>e.getBoundingClientRect().right<=innerWidth+1'))
        button('Review selection · 1').click()
        check('Large text primary label wraps inside actual production button', button('Save playlist').evaluate('e=>e.scrollWidth<=e.clientWidth+1'))
        name_input().fill('Large text keyboard draft')
        page.evaluate('window.__seanimeInsets={top:20,bottom:280};window.dispatchEvent(new Event("seanime:window-insets"))')
        check('Native keyboard inset keeps fixed save action above keyboard', button('Save playlist').evaluate('e=>e.getBoundingClientRect().bottom<=innerHeight-280+3'))
        page.evaluate('delete window.__seanimeInsets;document.documentElement.style.fontSize="";window.dispatchEvent(new Event("seanime:window-insets"))')
        sheet.locator('.mobile-workspace-close').click()
        page.evaluate('playlistProbe.update({playlists:[],selectedMedia:null,language:"de",open:true})')
        check('Localized empty state and creation action exist', sheet.get_by_text('Noch keine Playlists', exact=True).is_visible() and button('Playlist erstellen').is_visible())
        page.evaluate('playlistProbe.update({loading:true})')
        check('Playlist loading state is visible', sheet.get_by_role('status').is_visible())
        page.evaluate('playlistProbe.update({loading:false,error:true})')
        button('Erneut versuchen').click()
        check('Playlist load failure can recover', not page.evaluate('playlistProbe.state.error'))
        check('No uncaught browser exceptions', not errors)
        browser.close()
print(json.dumps(results, indent=2))
if len(sys.argv) > 1: Path(sys.argv[1]).write_text(json.dumps(results, indent=2), encoding='utf8')
